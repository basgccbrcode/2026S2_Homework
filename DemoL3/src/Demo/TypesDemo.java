package Demo;

public class TypesDemo {

	public static void main(String[] args) {
		int i = 9;
		System.out.println("Integer: " + i);
		
		float f = 3.2f;
		System.out.println("Float: " + f);
		
		double d = 3.2;
		System.out.println("Double: " + d);
		
		char c = 's';
		System.out.println("Char: " + c);
		
		boolean b = true;
		System.out.println("Bool: " + b);

	}

}
